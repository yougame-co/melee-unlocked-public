#!/usr/bin/env python3
"""Convert the source badge PNGs to GX RGBA8 (4x4 AR/GB tiles), using stdlib only.

Input is deliberately limited to 48x48, 8-bit RGBA, non-interlaced PNGs.
The PNGs, rather than YouGame site code, are the image source in this program.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SIZE = 48
TIERS = ('unranked', 'bronze', 'silver', 'gold', 'platinum', 'diamond')
NAMES = tuple(f'{tier}_{state}' for tier in TIERS for state in ('unplaced', 'placed')) + (
    'challenger', 'challenger_rays', 'challenger_core', 'challenger_star')
COLORS = ('0xb5c0cd', '0xc98a5b', '0xb5c0cd', '0xf0c040', '0x5fd8c8', '0x8cc8ff', '0xffc857')
PNG_DIR = ROOT/'sourceport/game/shim/assets/rank_badges'


def png_name(name):
    return name.removesuffix('_placed').replace('_', '-') + '.png'


def decode_png(data):
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('Invalid PNG signature')
    offset, compressed, seen_header, seen_end = 8, bytearray(), False, False
    while offset < len(data):
        if offset + 12 > len(data):
            raise ValueError('Truncated PNG chunk')
        length = struct.unpack_from('>I', data, offset)[0]
        kind = data[offset+4:offset+8]
        end = offset + 8 + length
        if end + 4 > len(data):
            raise ValueError('Truncated PNG chunk')
        payload = data[offset+8:end]
        if zlib.crc32(kind + payload) != struct.unpack_from('>I', data, end)[0]:
            raise ValueError('PNG checksum mismatch')
        if not seen_header and kind != b'IHDR':
            raise ValueError('PNG must begin with IHDR')
        if kind == b'IHDR':
            if seen_header or payload != struct.pack('>IIBBBBB', SIZE, SIZE, 8, 6, 0, 0, 0):
                raise ValueError('Expected 48x48 non-interlaced RGBA8 PNG')
            seen_header = True
        elif kind == b'IDAT':
            compressed.extend(payload)
        elif kind == b'IEND':
            if payload or end + 4 != len(data):
                raise ValueError('Invalid PNG end')
            seen_end = True
            break
        elif not kind[0] & 32:
            raise ValueError('Unsupported critical PNG chunk')
        offset = end + 4
    if not seen_end:
        raise ValueError('Missing PNG end')
    raw = zlib.decompress(compressed)
    stride = SIZE * 4
    if len(raw) != SIZE * (stride + 1):
        raise ValueError('Invalid PNG pixel data length')
    rgba, previous = bytearray(), bytearray(stride)
    for y in range(SIZE):
        pos = y * (stride + 1)
        mode = raw[pos]
        if mode > 4:
            raise ValueError('Unsupported PNG filter')
        row = bytearray(raw[pos+1:pos+1+stride])
        for x in range(stride):
            left = row[x-4] if x >= 4 else 0
            up = previous[x]
            corner = previous[x-4] if x >= 4 else 0
            if mode == 0: predictor = 0
            elif mode == 1: predictor = left
            elif mode == 2: predictor = up
            elif mode == 3: predictor = (left + up) // 2
            else:
                p = left + up - corner
                distances = (abs(p-left), abs(p-up), abs(p-corner))
                predictor = (left, up, corner)[distances.index(min(distances))]
            row[x] = (row[x] + predictor) & 255
        rgba.extend(row)
        previous = row
    return bytes(rgba)


def gx_tile(rgba):
    tiled = bytearray()
    for y in range(0, SIZE, 4):
        for x in range(0, SIZE, 4):
            pixels = [rgba[((y+j)*SIZE+x+i)*4:((y+j)*SIZE+x+i)*4+4] for j in range(4) for i in range(4)]
            tiled.extend(v for p in pixels for v in (p[3], p[0]))
            tiled.extend(v for p in pixels for v in (p[1], p[2]))
    return bytes(tiled)


def generate(png_dir=PNG_DIR):
    manifest = dict(width=SIZE, height=SIZE, format='GX_RGBA8', textures={})
    header = ['/* Generated by tools/rasterize_rank_badges.py. YouGame-owned art. */',
              '#ifndef MU_RANK_BADGE_ASSETS_H', '#define MU_RANK_BADGE_ASSETS_H',
              f'#define MU_RANK_BADGE_SIZE {SIZE}', f'#define MU_RANK_BADGE_TEXTURES {len(NAMES)}',
              '#ifdef __cplusplus', '#define MU_BADGE_ALIGN alignas(32)', '#else',
              '#define MU_BADGE_ALIGN _Alignas(32)', '#endif',
              'static const unsigned int mu_rank_tier_rgb[7] = {' + ','.join(COLORS) + '};']
    for name in NAMES:
        data = (png_dir/png_name(name)).read_bytes()
        rgba = decode_png(data); tiled = gx_tile(rgba)
        manifest['textures'][name] = dict(png=png_name(name), png_sha256=hashlib.sha256(data).hexdigest(), rgba_sha256=hashlib.sha256(rgba).hexdigest(), gx_sha256=hashlib.sha256(tiled).hexdigest())
        header.append(f'MU_BADGE_ALIGN static const unsigned char mu_badge_{name}[] = {{')
        header.extend('    ' + ','.join(str(v) for v in tiled[i:i+32]) + ',' for i in range(0, len(tiled), 32))
        header.append('};')
    header.append('static const unsigned char* const mu_badge_textures[] = {' + ','.join('mu_badge_' + name for name in NAMES) + '};')
    header.extend(['#undef MU_BADGE_ALIGN', '#endif', ''])
    return '\n'.join(header), json.dumps(manifest, indent=2) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--png-dir', type=Path, default=PNG_DIR)
    p.add_argument('--output', type=Path, default=ROOT/'sourceport/game/shim/assets/mu_rank_badges.h')
    p.add_argument('--manifest', type=Path, default=ROOT/'tools/rank_badges/checksums.json')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    header, manifest = generate(args.png_dir)
    for path, data in ((args.output, header), (args.manifest, manifest)):
        if args.check:
            if not path.exists() or path.read_text() != data: raise SystemExit(f'Stale badge asset: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != data: path.write_text(data)
    print(f'YouGame badges: {SIZE}x{SIZE}, 16 textures, {"verified" if args.check else "baked"}')


if __name__ == '__main__': main()
